#!/usr/bin/env python3
"""Verify pinned offline PDF assets and generate the strict Android asset list."""
from pathlib import Path, PurePosixPath
import hashlib
import json

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "companion" / "wwwroot"
MANIFEST = ROOT / "scripts" / "notebook-pdf-vendor.json"
OUTPUT = ROOT / "android" / "src" / "app" / "tabletdeck" / "NotebookUiAssets.java"
BOOTSTRAP = ("notebook-ui.js", "notebook-pdf.js", "notebook-store.js", "notebook-recovery.js", "privacy-support.js")


def verified_vendor_assets():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8-sig"))
    entries = manifest.get("assets")
    if not isinstance(entries, list) or not 1 <= len(entries) <= 512:
        raise ValueError("Invalid offline PDF asset count")
    seen, paths, total = set(), [], 0
    for entry in entries:
        name = entry.get("path", "")
        relative = PurePosixPath(name)
        if (not name or relative.is_absolute() or ".." in relative.parts
                or any(value in name for value in ("\\", ":", "?", "#"))
                or not name.startswith(("vendor/pdfjs/", "vendor/pdf-lib/"))
                or name.casefold() in seen):
            raise ValueError("Unsafe or duplicate offline PDF asset")
        source = (WEB / name).resolve()
        if not source.is_relative_to(WEB.resolve()) or not source.is_file():
            raise ValueError("Missing offline PDF asset")
        data = source.read_bytes()
        if len(data) != entry.get("bytes") or len(data) > 12 * 1024 * 1024:
            raise ValueError("Offline PDF asset size mismatch")
        if hashlib.sha256(data).hexdigest() != entry.get("sha256"):
            raise ValueError("Offline PDF asset checksum mismatch")
        total += len(data)
        if total > 64 * 1024 * 1024:
            raise ValueError("Offline PDF assets exceed bundle budget")
        seen.add(name.casefold())
        paths.append(name)
    return sorted(paths)


def main():
    names = sorted(set(verified_vendor_assets()) | set(BOOTSTRAP))
    for name in BOOTSTRAP:
        if not (WEB / name).is_file():
            raise ValueError("Missing notebook bootstrap asset")
    lines = ",\n".join("        " + json.dumps("/" + name) for name in names)
    content = (
        "package app.tabletdeck;\n\n"
        "import java.util.Arrays;\nimport java.util.HashSet;\nimport java.util.Set;\n\n"
        "// Generated by scripts/sync-notebook-assets.py from checksum-verified local assets.\n"
        "final class NotebookUiAssets {\n"
        "    static final Set<String> PATHS=new HashSet<>(Arrays.asList(\n"
        + lines + "\n    ));\n"
        "    private NotebookUiAssets() { }\n}\n"
    )
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Verified {len(names) - len(BOOTSTRAP)} PDF assets; generated {len(names)} allowed paths.")


if __name__ == "__main__":
    main()
